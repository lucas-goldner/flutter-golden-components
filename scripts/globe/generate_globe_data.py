"""Generates lib/src/globe/globe_data.dart from Natural Earth admin-0 countries.

Natural Earth data is in the public domain.

Usage:
  curl -sSLO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
  python3 -I scripts/globe/generate_globe_data.py ne_50m_admin_0_countries.geojson lib/src/globe/globe_data.dart

The sphere is sampled in latitude rings (dots evenly spaced along each ring,
fewer towards the poles). Every sample is tagged with the country it falls in
(0 = ocean); each ring is run-length encoded and the whole stream is
base64'd into a Dart string, so the package ships no binary assets.
"""

import base64
import json
import math
import sys

import numpy as np

RINGS = 180  # rings from pole to pole: ~1 degree apart

CONTINENTS = {
    'Africa': 0,
    'Antarctica': 1,
    'Asia': 2,
    'Europe': 3,
    'North America': 4,
    'Oceania': 5,
    'South America': 6,
    'Seven seas (open ocean)': 5,
}


def samples():
    """Yields (ring, lat, lngs[]) for every ring, lng in degrees."""
    for r in range(RINGS):
        lat = 90 - (r + 0.5) * 180 / RINGS
        n = max(1, round(2 * RINGS * math.cos(math.radians(lat))))
        lngs = -180 + (np.arange(n) + 0.5) * 360 / n
        yield r, lat, lngs


def point_in_ring(px, py, ring):
    """Vectorised even-odd test of points against one polygon ring."""
    xs = ring[:, 0]
    ys = ring[:, 1]
    inside = np.zeros(px.shape, dtype=bool)
    x1, y1 = xs[-1], ys[-1]
    for x2, y2 in zip(xs, ys):
        cond = (y1 > py) != (y2 > py)
        with np.errstate(divide='ignore', invalid='ignore'):
            xint = (x2 - x1) * (py - y1) / (y2 - y1) + x1
        inside ^= cond & (px < xint)
        x1, y1 = x2, y2
    return inside


def polygons(geometry):
    if geometry['type'] == 'Polygon':
        return [geometry['coordinates']]
    if geometry['type'] == 'MultiPolygon':
        return geometry['coordinates']
    return []


def polygon_centroid(ring):
    """Area and (lng, lat) centroid of a ring (planar, fine for one country)."""
    x, y = ring[:, 0], ring[:, 1]
    cross = x * np.roll(y, -1) - np.roll(x, -1) * y
    area = cross.sum() / 2
    if abs(area) < 1e-12:
        return 0.0, (float(x.mean()), float(y.mean()))
    cx = ((x + np.roll(x, -1)) * cross).sum() / (6 * area)
    cy = ((y + np.roll(y, -1)) * cross).sum() / (6 * area)
    return abs(area), (float(cx), float(cy))


def code_of(props):
    for key in ('ISO_A3_EH', 'ISO_A3', 'ADM0_A3'):
        value = props.get(key)
        if value and value != '-99':
            return value
    return props['ADM0_A3']


def main(src, out):
    features = json.load(open(src))['features']
    countries = []  # (code, name, continent)
    centres = []  # (lat, lng) of each country's largest polygon
    shapes = []  # list of (index, [rings as np arrays], bbox)
    for f in sorted(features, key=lambda f: code_of(f['properties'])):
        p = f['properties']
        index = len(countries) + 1
        countries.append((code_of(p), p['NAME'], CONTINENTS.get(p['CONTINENT'], 5)))
        best = max(
            (polygon_centroid(np.array(poly[0], dtype=np.float64)) for poly in polygons(f['geometry'])),
            default=(0, (0.0, 0.0)),
        )
        centres.append((best[1][1], best[1][0]))
        for poly in polygons(f['geometry']):
            rings = [np.array(r, dtype=np.float64) for r in poly]
            outer = rings[0]
            bbox = (outer[:, 0].min(), outer[:, 1].min(), outer[:, 0].max(), outer[:, 1].max())
            shapes.append((index, rings, bbox))

    stream = bytearray()
    land = 0
    for r, lat, lngs in samples():
        owner = np.zeros(len(lngs), dtype=np.int32)
        py = np.full(len(lngs), lat)
        for index, rings, (x0, y0, x1, y1) in shapes:
            if lat < y0 or lat > y1:
                continue
            mask = (lngs >= x0) & (lngs <= x1) & (owner == 0)
            if not mask.any():
                continue
            px = lngs[mask]
            hit = point_in_ring(px, py[mask], rings[0])
            for hole in rings[1:]:
                hit &= ~point_in_ring(px, py[mask], hole)
            idx = np.nonzero(mask)[0][hit]
            owner[idx] = index
        # Run-length encode: [country byte][run length byte] pairs.
        i = 0
        while i < len(owner):
            c = int(owner[i])
            j = i
            while j < len(owner) and owner[j] == c and j - i < 255:
                j += 1
            stream += bytes([c, j - i])
            i = j
        land += int((owner > 0).sum())

    encoded = base64.b64encode(bytes(stream)).decode()
    lines = [encoded[i:i + 96] for i in range(0, len(encoded), 96)]
    with open(out, 'w') as f:
        f.write('// GENERATED by scripts/globe/generate_globe_data.py. Do not edit.\n')
        f.write('// Country shapes: Natural Earth 1:50m admin-0 countries (public domain).\n')
        f.write('// ignore_for_file: public_member_api_docs\n\n')
        f.write('/// Number of latitude rings the sphere is sampled with.\n')
        f.write(f'const int globeRings = {RINGS};\n\n')
        f.write('/// Countries as (ISO 3166-1 alpha-3 code, name, continent index, centre lat,\n')
        f.write('/// centre lng). Index i + 1 in [globeSamples] refers to entry i.\n')
        f.write('const List<(String, String, int, double, double)> globeCountries = [\n')
        for (code, name, cont), centre in zip(countries, centres):
            lat, lng = centre
            name = name.replace("'", "\\'")
            f.write(f"  ('{code}', '{name}', {cont}, {lat:.2f}, {lng:.2f}),\n")
        f.write('];\n\n')
        f.write('/// Run-length encoded country index per sample, ring by ring, as\n')
        f.write('/// base64 (country byte, run length byte) pairs; 0 is ocean.\n')
        f.write('const String globeSamples =\n')
        for k, line in enumerate(lines):
            end = ';' if k == len(lines) - 1 else ''
            f.write(f"    '{line}'{end}\n")
    print(f'{len(countries)} countries, {land} land dots, {len(encoded)} base64 chars')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
